export type FloorNumber = 1 | 2 | 3 | 4;

export type NodeKind =
  | 'parking'
  | 'room'
  | 'corridor'
  | 'stairs'
  | 'elevator'
  | 'facility'
  | 'gate';

export interface CampusNode {
  id: string;
  label: string;
  shortLabel?: string;
  floor: FloorNumber;
  x: number; // SVG coordinate (0..360)
  y: number; // SVG coordinate (0..400)
  kind: NodeKind;
  description?: string;
  landmark?: string;
  /** Bounding box for clickable room/area polygons in 2D map */
  box?: {
    x: number;
    y: number;
    w: number;
    h: number;
  };
}

export interface CampusEdge {
  from: string;
  to: string;
  distanceMeters: number;
  /** Requires climbing/descending stairs (excluded in Lift/Accessible mode) */
  isStairs?: boolean;
  /** Uses campus elevator */
  isElevator?: boolean;
  /** Natural Indonesian instruction when walking from -> to */
  instructionForward: string;
  /** Natural Indonesian instruction when walking to -> from */
  instructionBackward: string;
  landmarkHint?: string;
}

export interface ParkingSpot {
  id: string;
  nodeId: string;
  name: string;
  vehicleType: 'Motor' | 'Mobil';
  areaHint: string;
  badgeColor: string;
}

export interface CourseSchedule {
  id: string;
  code: string;
  name: string;
  lecturer: string;
  day: 'Senin' | 'Selasa' | 'Rabu' | 'Kamis' | 'Jumat' | 'Sabtu';
  startTime: string;
  endTime: string;
  roomId: string;
  classCode: string;
  prodi: 'TI' | 'DKV' | 'BD' | 'SK';
  isUpcoming?: boolean;
}

export interface StudentProfile {
  id: string;
  name: string;
  nim: string;
  prodi: 'TI' | 'DKV' | 'Umum';
  prodiLabel: string;
  semester: number;
  defaultParkingId: string;
  isGuest?: boolean;
}

